/**
 * Postgres baseline: the exact layout the SQLite database had after migration 11,
 * translated 1:1 so a SQLite backup copies straight in (script/import-sqlite.ts).
 *
 *  - INTEGER  -> bigint (ids, counts, 1/0 flags, millisecond timestamps all fit)
 *  - REAL     -> double precision (money stays the same JS number it was in SQLite)
 *  - TEXT     -> text (dates and times stay ISO strings, as before)
 *  - Yes/no columns stay 1/0 so every existing query (`active=1`) works unchanged.
 *  - Foreign keys are DEFERRABLE so an import can load tables in any order inside
 *    one transaction and have every link checked at COMMIT.
 *
 * Never edit this to change the schema: add a numbered migration in server/migrations.ts.
 */
export const BASELINE_VERSION = 11;

const id = "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
const ref = (table: string, col = "id") => `REFERENCES ${table}(${col}) DEFERRABLE INITIALLY IMMEDIATE`;

export const BASELINE_SQL = `
CREATE TABLE organization (id text PRIMARY KEY, singleton bigint UNIQUE NOT NULL CHECK (singleton = 1));

CREATE TABLE app_settings (
  ${id},
  business_name text NOT NULL DEFAULT 'Mad River Cleaning Co.',
  business_address text NOT NULL DEFAULT '',
  business_phone text NOT NULL DEFAULT '',
  business_email text NOT NULL DEFAULT '',
  logo_placeholder text,
  default_tax_rate double precision NOT NULL DEFAULT 0,
  default_payment_terms_days bigint NOT NULL DEFAULT 15,
  invoice_number_prefix text NOT NULL DEFAULT 'INV',
  invoice_footer_note text NOT NULL DEFAULT 'Thank you for your business.',
  notify_job_reminders bigint NOT NULL DEFAULT 1,
  notify_invoice_overdue bigint NOT NULL DEFAULT 1,
  notify_payment_received bigint NOT NULL DEFAULT 1,
  notify_daily_digest bigint NOT NULL DEFAULT 0
);

CREATE TABLE staff (
  ${id}, name text NOT NULL, role text NOT NULL, email text NOT NULL, phone text NOT NULL,
  color_tag text NOT NULL, active bigint NOT NULL DEFAULT 1
);

CREATE TABLE customers (
  ${id}, name text NOT NULL, company_name text, customer_type text NOT NULL, email text NOT NULL,
  phone text NOT NULL, alt_phone text, preferred_contact text NOT NULL,
  billing_address_line1 text NOT NULL, billing_address_line2 text, billing_city text NOT NULL,
  billing_state text NOT NULL, billing_zip text NOT NULL, notes text,
  tax_exempt bigint NOT NULL DEFAULT 0, created_at text NOT NULL DEFAULT ''
);

CREATE TABLE contacts (
  ${id}, customer_id bigint NOT NULL ${ref("customers")}, name text NOT NULL, role text,
  email text NOT NULL, phone text NOT NULL, is_primary bigint NOT NULL DEFAULT 0
);

CREATE TABLE subcontractors (
  ${id}, name text NOT NULL, business_name text, email text, phone text, services text,
  pay_type text NOT NULL DEFAULT 'per_job' CHECK (pay_type IN ('per_job','hourly')), default_pay double precision,
  w9_on_file bigint NOT NULL DEFAULT 0, insurance_expires text, notes text,
  active bigint NOT NULL DEFAULT 1, created_at text NOT NULL, updated_at text NOT NULL
);

CREATE TABLE job_templates (
  ${id}, name text NOT NULL, job_type text NOT NULL, default_duration_minutes bigint NOT NULL,
  default_price double precision NOT NULL, default_checklist text NOT NULL, description text
);

CREATE TABLE properties (
  ${id}, customer_id bigint NOT NULL ${ref("customers")}, name text NOT NULL, address_line1 text NOT NULL,
  address_line2 text, city text NOT NULL, state text NOT NULL, zip text NOT NULL, unit_type text NOT NULL,
  bedrooms bigint NOT NULL, bathrooms double precision NOT NULL, max_occupancy bigint NOT NULL,
  check_in_time text NOT NULL, check_out_time text NOT NULL, entry_instructions text NOT NULL,
  access_notes text, supply_notes text, cleaning_frequency text NOT NULL, base_price double precision NOT NULL,
  photo_url text, active bigint NOT NULL DEFAULT 1,
  full_bathrooms bigint CHECK (full_bathrooms >= 0), half_bathrooms bigint CHECK (half_bathrooms >= 0),
  legacy_total_bathrooms double precision,
  standard_departure_rate double precision CHECK (standard_departure_rate >= 0),
  standard_departure_rate_name text DEFAULT 'Standard Departure Cleaning',
  owner_rate double precision CHECK (owner_rate >= 0), owner_rate_name text DEFAULT 'Owner Departure Cleaning',
  invoice_notes text,
  bed_king bigint NOT NULL DEFAULT 0, bed_queen bigint NOT NULL DEFAULT 0, bed_full bigint NOT NULL DEFAULT 0,
  bed_twin bigint NOT NULL DEFAULT 0, bed_bunk bigint NOT NULL DEFAULT 0, bed_sofa bigint NOT NULL DEFAULT 0
);

CREATE TABLE schedules (
  ${id}, property_id bigint NOT NULL ${ref("properties")}, job_template_id bigint ${ref("job_templates")},
  frequency text NOT NULL, day_of_week bigint, start_date text NOT NULL, end_date text,
  assigned_staff_id bigint ${ref("staff")}, active bigint NOT NULL DEFAULT 1
);

CREATE TABLE jobs (
  ${id}, property_id bigint NOT NULL ${ref("properties")}, customer_id bigint NOT NULL ${ref("customers")},
  schedule_id bigint ${ref("schedules")}, job_template_id bigint ${ref("job_templates")},
  job_type text NOT NULL, scheduled_date text NOT NULL, scheduled_time text NOT NULL,
  duration_minutes bigint NOT NULL, assigned_staff_id bigint ${ref("staff")},
  status text NOT NULL DEFAULT 'scheduled', internal_notes text, customer_notes text,
  price double precision NOT NULL, before_photos text NOT NULL DEFAULT '[]', after_photos text NOT NULL DEFAULT '[]',
  completed_at text, rate_type text NOT NULL DEFAULT 'custom', damage_notes text
);
CREATE INDEX jobs_assigned_staff ON jobs (assigned_staff_id);
CREATE INDEX jobs_scheduled_date ON jobs (scheduled_date);

CREATE TABLE service_checklists (
  ${id}, job_id bigint NOT NULL ${ref("jobs")}, label text NOT NULL,
  is_completed bigint NOT NULL DEFAULT 0, sort_order bigint NOT NULL DEFAULT 0
);
CREATE INDEX service_checklists_job ON service_checklists (job_id);

CREATE TABLE stays (
  ${id}, property_id bigint NOT NULL ${ref("properties")}, guest_name text NOT NULL, guest_phone text,
  guest_count bigint, platform text NOT NULL DEFAULT 'airbnb', check_in_date text NOT NULL,
  check_out_date text NOT NULL, status text NOT NULL DEFAULT 'confirmed', notes text, created_at text NOT NULL
);

CREATE TABLE notes (
  ${id}, customer_id bigint ${ref("customers")}, property_id bigint ${ref("properties")}, job_id bigint ${ref("jobs")},
  author_staff_id bigint ${ref("staff")}, body text NOT NULL, pinned bigint NOT NULL DEFAULT 0, created_at text NOT NULL DEFAULT ''
);

CREATE TABLE attachments (
  ${id}, entity_type text NOT NULL, entity_id bigint NOT NULL, file_name text NOT NULL,
  file_path text NOT NULL, category text NOT NULL, uploaded_at text NOT NULL DEFAULT ''
);

CREATE TABLE service_catalog (
  ${id}, name text NOT NULL, description text NOT NULL DEFAULT '', category text NOT NULL DEFAULT 'Other',
  default_price double precision NOT NULL CHECK (default_price >= 0),
  default_quantity double precision NOT NULL DEFAULT 1 CHECK (default_quantity > 0),
  unit text NOT NULL DEFAULT 'service', active bigint NOT NULL DEFAULT 1,
  default_inclusion_behavior text NOT NULL DEFAULT 'suggested', taxable bigint NOT NULL DEFAULT 0,
  sort_order bigint NOT NULL DEFAULT 0, created_at text NOT NULL, updated_at text NOT NULL
);

CREATE TABLE property_services (
  ${id}, property_id bigint NOT NULL ${ref("properties")}, service_id bigint ${ref("service_catalog")},
  custom_name text NOT NULL, custom_description text NOT NULL DEFAULT '',
  custom_price double precision NOT NULL CHECK (custom_price >= 0),
  default_quantity double precision NOT NULL DEFAULT 1 CHECK (default_quantity > 0),
  enabled bigint NOT NULL DEFAULT 1, invoice_behavior text NOT NULL DEFAULT 'suggested',
  internal_notes text NOT NULL DEFAULT '', excludes_property_service_id bigint ${ref("property_services")},
  created_at text NOT NULL, updated_at text NOT NULL
);
CREATE UNIQUE INDEX property_catalog_service ON property_services (property_id, service_id) WHERE service_id IS NOT NULL;

CREATE TABLE invoices (
  ${id}, customer_id bigint NOT NULL ${ref("customers")}, job_id bigint ${ref("jobs")},
  invoice_number text NOT NULL, issue_date text NOT NULL, due_date text NOT NULL, status text NOT NULL DEFAULT 'draft',
  subtotal double precision NOT NULL DEFAULT 0, discount_amount double precision NOT NULL DEFAULT 0,
  tax_rate double precision NOT NULL DEFAULT 0, tax_amount double precision NOT NULL DEFAULT 0,
  travel_fee double precision NOT NULL DEFAULT 0, rush_fee double precision NOT NULL DEFAULT 0,
  total double precision NOT NULL DEFAULT 0, amount_paid double precision NOT NULL DEFAULT 0,
  notes text, property_id bigint ${ref("properties")}, rate_type text NOT NULL DEFAULT 'custom',
  property_address text, customer_snapshot text, internal_notes text, sent_at text, viewed_at text, paid_at text,
  public_token text, public_enabled bigint NOT NULL DEFAULT 0, request_key text, created_at text, updated_at text
);
CREATE UNIQUE INDEX invoices_invoice_number_unique ON invoices (invoice_number);
CREATE UNIQUE INDEX invoice_public_token ON invoices (public_token) WHERE public_token IS NOT NULL;
CREATE UNIQUE INDEX invoice_request_key ON invoices (request_key) WHERE request_key IS NOT NULL;
CREATE INDEX invoices_customer ON invoices (customer_id);
CREATE INDEX invoices_job ON invoices (job_id);

CREATE TABLE invoice_items (
  ${id}, invoice_id bigint NOT NULL ${ref("invoices")}, description text NOT NULL, item_type text NOT NULL,
  quantity double precision NOT NULL DEFAULT 1, unit_price double precision NOT NULL, amount double precision NOT NULL,
  sort_order bigint NOT NULL DEFAULT 0, source_property_service_id bigint, description_snapshot text,
  is_auto_added bigint NOT NULL DEFAULT 0, line_item_type text NOT NULL DEFAULT 'manual'
);
CREATE INDEX invoice_items_invoice ON invoice_items (invoice_id);

CREATE TABLE payments (
  ${id}, invoice_id bigint NOT NULL ${ref("invoices")}, amount double precision NOT NULL, method text NOT NULL,
  paid_date text NOT NULL, reference text, provider text, provider_transaction_id text, note text,
  status text NOT NULL DEFAULT 'succeeded', request_key text, created_at text
);
CREATE UNIQUE INDEX payment_request_key ON payments (request_key) WHERE request_key IS NOT NULL;
CREATE UNIQUE INDEX payment_transaction ON payments (provider, provider_transaction_id) WHERE provider_transaction_id IS NOT NULL;
CREATE INDEX payments_invoice ON payments (invoice_id);

CREATE TABLE invoice_activity (
  ${id}, invoice_id bigint NOT NULL ${ref("invoices")}, activity_type text NOT NULL, actor text NOT NULL,
  details text NOT NULL, created_at text NOT NULL
);
CREATE INDEX invoice_activity_invoice ON invoice_activity (invoice_id);

CREATE TABLE invoice_sends (
  request_key text PRIMARY KEY, invoice_id bigint NOT NULL ${ref("invoices")}, payload text NOT NULL,
  status text NOT NULL DEFAULT 'pending', provider_id text, created_at text NOT NULL, review_data text
);

CREATE TABLE checkout_sessions (
  id text PRIMARY KEY, invoice_id bigint NOT NULL ${ref("invoices")}, amount_cents bigint NOT NULL,
  provider_id text UNIQUE, url text, status text NOT NULL DEFAULT 'creating', expires_at bigint NOT NULL, created_at text NOT NULL
);
CREATE UNIQUE INDEX one_active_checkout ON checkout_sessions (invoice_id) WHERE status IN ('creating','open');

CREATE TABLE webhook_events (id text PRIMARY KEY, created_at text NOT NULL);

CREATE TABLE deleted_invoices (
  ${id}, invoice_id bigint NOT NULL, invoice_number text NOT NULL, snapshot text NOT NULL,
  deleted_by text NOT NULL, deleted_at text NOT NULL
);

CREATE TABLE expenses (
  ${id}, kind text NOT NULL CHECK (kind IN ('mileage','supply')), expense_date text NOT NULL,
  description text NOT NULL, category text NOT NULL, vendor text, amount double precision NOT NULL CHECK (amount >= 0),
  miles double precision, round_trip bigint NOT NULL DEFAULT 0, total_miles double precision, rate_per_mile double precision,
  from_location text, to_location text, property_id bigint ${ref("properties")}, job_id bigint ${ref("jobs")},
  payment_method text, notes text, created_at text NOT NULL, created_by text NOT NULL, updated_at text NOT NULL
);
CREATE INDEX expenses_date ON expenses (expense_date);

CREATE TABLE expense_receipts (
  ${id}, expense_id bigint NOT NULL ${ref("expenses")}, file_name text NOT NULL UNIQUE, original_name text NOT NULL,
  size bigint NOT NULL, created_at text NOT NULL, created_by text NOT NULL
);
CREATE INDEX expense_receipts_expense ON expense_receipts (expense_id);

CREATE TABLE job_photos (
  ${id}, job_id bigint NOT NULL ${ref("jobs")}, section text NOT NULL CHECK (section IN ('damage','final_walkthrough')),
  file_name text NOT NULL UNIQUE, original_name text NOT NULL, size bigint NOT NULL, created_at text NOT NULL, created_by text NOT NULL
);
CREATE INDEX job_photos_job ON job_photos (job_id, section);

CREATE TABLE job_subcontractors (
  job_id bigint PRIMARY KEY ${ref("jobs")}, subcontractor_id bigint NOT NULL ${ref("subcontractors")},
  pay double precision NOT NULL CHECK (pay >= 0), assigned_at text NOT NULL, assigned_by text NOT NULL
);
CREATE INDEX job_subcontractors_sub ON job_subcontractors (subcontractor_id);

CREATE TABLE subcontractor_payments (
  ${id}, subcontractor_id bigint NOT NULL ${ref("subcontractors")}, paid_date text NOT NULL,
  amount double precision NOT NULL CHECK (amount > 0), method text, reference text, job_id bigint ${ref("jobs")},
  note text, created_at text NOT NULL, created_by text NOT NULL
);
CREATE INDEX subcontractor_payments_sub ON subcontractor_payments (subcontractor_id, paid_date);

CREATE TABLE calendar_feeds (
  ${id}, token text NOT NULL UNIQUE, token_hash text NOT NULL UNIQUE, created_at text NOT NULL,
  created_by text NOT NULL, revoked_at text, last_fetched_at text
);
CREATE TABLE calendar_sources (
  ${id}, name text NOT NULL, url text NOT NULL UNIQUE, color text NOT NULL, active bigint NOT NULL DEFAULT 1,
  last_synced_at text, last_attempt_at text, last_error text, event_count bigint NOT NULL DEFAULT 0,
  created_at text NOT NULL, created_by text NOT NULL
);
CREATE TABLE calendar_events (
  ${id}, source_id bigint NOT NULL ${ref("calendar_sources")}, uid text NOT NULL, title text NOT NULL, location text,
  all_day bigint NOT NULL DEFAULT 0, start_at text NOT NULL, end_at text NOT NULL, start_day text NOT NULL, end_day text NOT NULL
);
CREATE INDEX calendar_events_days ON calendar_events (start_day, end_day);
CREATE INDEX calendar_events_source ON calendar_events (source_id);

CREATE TABLE auth_users (
  id text PRIMARY KEY, organization_id text NOT NULL ${ref("organization")}, email text NOT NULL UNIQUE,
  password_hash text NOT NULL, active bigint NOT NULL DEFAULT 1,
  role text NOT NULL DEFAULT 'owner' CHECK (role IN ('owner','cleaner')),
  staff_id bigint ${ref("staff")}, subcontractor_id bigint ${ref("subcontractors")}
);
CREATE UNIQUE INDEX auth_users_staff ON auth_users (staff_id) WHERE staff_id IS NOT NULL;
CREATE UNIQUE INDEX auth_users_subcontractor ON auth_users (subcontractor_id) WHERE subcontractor_id IS NOT NULL;
CREATE TABLE auth_sessions (token_hash text PRIMARY KEY, user_id text NOT NULL ${ref("auth_users")}, expires_at bigint NOT NULL);
CREATE TABLE auth_rate_limits (key text PRIMARY KEY, count bigint NOT NULL, resets_at bigint NOT NULL);

CREATE TABLE maintenance_log (version bigint PRIMARY KEY, result text NOT NULL, created_at text NOT NULL);
`;

